export function endpointFor(feature: AppFeature): string {
  return FEATURE_ENDPOINT[feature];
}

export function endpointForJobDownload(jobId: string): string {
  return endpointFor(AppFeature.JOBS_DOWNLOAD).replace('[id]', encodeURIComponent(jobId));
}

export function endpointForJobRetry(jobId: string): string {
  return endpointFor(AppFeature.JOBS_RETRY).replace('[id]', encodeURIComponent(jobId));
}

export function endpointForJobDetail(jobId: string): string {
  return endpointFor(AppFeature.JOBS_GET_ONE).replace('[id]', encodeURIComponent(jobId));
}
