import * as React from 'react';

import { cn } from '@/app/lib/utils';

const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        // Soft floating shadow in light (reads as a lift off the cool ground);
        // in dark the near-black shadow all but vanishes, so the border + a
        // card fill one step lighter than the background carry the separation.
        'rounded-xl border bg-card text-card-foreground shadow-[0_1px_2px_rgba(15,23,42,0.04),0_12px_30px_-14px_rgba(15,23,42,0.12)]',
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = 'Card';

