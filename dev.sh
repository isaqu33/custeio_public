#!/bin/bash
set -euo pipefail

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SCRIPT_DIR}/.env"
ENV_LOCAL_FILE="${SCRIPT_DIR}/.env.local"
COMPOSE_FILE="${SCRIPT_DIR}/docker-compose.dev.yml"

info() {
  printf "${GREEN}%s${NC}\n" "$1"
}

warn() {
  printf "${YELLOW}%s${NC}\n" "$1"
}

fail() {
  printf "${RED}%s${NC}\n" "$1"
  exit 1
}

require_command() {
  if ! command -v "$1" >/dev/null 2>&1; then
    fail "Missing required command: $1"
  fi
}

write_env_local() {
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a

  cat > "$ENV_LOCAL_FILE" <<EOF
# Generated by ./dev.sh — overrides .env when Next runs on the host.
# Mongo + Redis are reached at localhost via docker-compose.dev.yml published ports.
DATABASE_URL=mongodb://${MONGO_USERNAME}:${MONGO_PASSWORD}@localhost:${MONGO_PORT_HOST:-27030}/custeio?authSource=admin
REDIS_HOST=localhost
REDIS_PORT=6400
REDIS_URL=redis://:${REDIS_PASSWORD}@localhost:6400
APP_AZURE_STORAGE_CONNECTION_STRING=DefaultEndpointsProtocol=http;AccountName=devstoreaccount1;AccountKey=Eby8vdM02xNOcqFlqUwJPLlmEtlCDXJ1OUzFT50uSRZ6IFsuFq2UVErCz4I6tq/K1SZFPTOtr/KBHBeksoGMGw==;BlobEndpoint=http://127.0.0.1:10020/devstoreaccount1;
EOF
}

env_local_needs_update() {
  if [ "${DEV_REWRITE_ENV_LOCAL:-false}" = "true" ]; then
    return 0
  fi
  if [ ! -f "$ENV_LOCAL_FILE" ]; then
    return 0
  fi
  if ! grep -q '^APP_AZURE_STORAGE_CONNECTION_STRING=' "$ENV_LOCAL_FILE"; then
    return 0
  fi
  return 1
}

cd "$SCRIPT_DIR"

info "Starting Custeio dev (host)..."

require_command docker
require_command npm

# 1. Ensure .env exists.
"${SCRIPT_DIR}/scripts/dev/init-env.sh" "$ENV_FILE"

# 2. Generate .env.local for host overrides if missing.
# Next reads .env then .env.local (later wins), so this only needs the deltas.
# Mongo + Redis live in containers; we point at their published ports on the host.
if env_local_needs_update; then
  warn "Generating .env.local with host-side datastore overrides..."
  write_env_local
fi

# 3. Bring up local dependencies and wait for healthchecks where available.
warn "Starting mongo + redis + azurite..."
if ! docker compose -f "$COMPOSE_FILE" up -d --wait mongo redis azurite; then
  fail "DEV dependencies failed to start. Run: docker compose -f docker-compose.dev.yml logs mongo redis azurite"
fi

# 4. Install deps on first run.
if [ ! -d node_modules ]; then
  warn "Installing dependencies..."
  npm install
fi

# 5. Hand off to Next dev.
info "Stack ready. Launching Next dev on http://localhost:3030"
exec npm run dev -- -p 3030
