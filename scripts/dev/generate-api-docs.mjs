// Generates docs/api.md from the route files themselves, so the API reference can
// never drift from the code: every `app/api/**/route.ts` is read for the HTTP
// methods it exports and the feature id it registers with `withObservability`.
//
//   npm run docs:api
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const apiDir = join(root, 'app/api');

function* routes(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* routes(path);
    else if (name === 'route.ts') yield path;
  }
}

const rows = [];
for (const file of routes(apiDir)) {
  const source = readFileSync(file, 'utf8');
  const route =
    '/api/' +
    relative(apiDir, file)
      .replace(`${sep}route.ts`, '')
      .replace(/^route\.ts$/, '')
      .split(sep)
      .join('/');
  const methods = [
    ...source.matchAll(/export (?:const|async function|function) (GET|POST|PUT|PATCH|DELETE)\b/g),
  ].map((m) => m[1]);
  const feature = source.match(/AppFeature\.([A-Z_]+)/)?.[1]?.toLowerCase() ?? '';
  // Classified from what the file actually calls, never assumed.
  let access = 'no session';
  if (route.startsWith('/api/auth/')) access = 'Auth.js handler';
  else if (route.startsWith('/api/v1/webhooks/')) access = 'webhook key (hashed), no session';
  else if (route === '/api/organizations/claim') access = 'invite token, no session';
  else if (/requireSystemAccess|requireHumanSystemAccess/.test(source)) access = 'platform admin';
  else if (/\brequire[A-Za-z]+\(|\bauth\(\)|getAuthorizedOrganizationIds/.test(source))
    access = 'signed-in user (org-scoped)';
  for (const method of methods)
    rows.push({ route: route.replace(/\/$/, ''), method, feature, access });
}

rows.sort((a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method));

const lines = [
  '# API reference',
  '',
  '> Generated by `npm run docs:api` from `app/api/**/route.ts` — do not edit by hand.',
  '',
  'Every route answers with `{ done, data?, message?, error? }`. Routes under `/api/organizations/*`',
  "and the operational ones are scoped to the caller's organization; the tenant is **never** taken",
  'from the request body without being checked against the session (see `docs/architecture/`).',
  '',
  `${rows.length} endpoints.`,
  '',
  '| Method | Route | Feature | Access |',
  '| ------ | ----- | ------- | ------ |',
  ...rows.map(
    (r) =>
      `| ${r.method} | \`${r.route}\` | ${r.feature ? `\`${r.feature}\`` : '—'} | ${r.access} |`,
  ),
  '',
];
writeFileSync(join(root, 'docs/api.md'), lines.join('\n'));
console.log(`docs/api.md: ${rows.length} endpoints`);
